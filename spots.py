import json
import os

base_dir = os.path.dirname(__file__)

def _load_json(filename):
    path = os.path.join(base_dir, filename)
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception as e:
        print(f"[Error] Failed to load {filename}: {e}")
        return {}

